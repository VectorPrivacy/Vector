#!/usr/bin/env node
/**
 * build-twemoji-sheets.mjs — Pack the picker's stock emoji into sprite sheets.
 *
 * Each emoji in src/js/emoji.js, in picker order, is rendered from its twemoji SVG
 * (by the core's own resvg) into src/twemoji/sheets/<n>.webp, and
 * src/js/emoji/sheets.js maps each emoji to its slot. The picker paints a cell as a
 * slice of one sheet: a few decoded images for the whole grid, where an <img> per
 * emoji made WebKit hold a document per SVG.
 *
 * Usage: node scripts/build-twemoji-sheets.mjs [cell px] [out dir]
 * Re-run after build-emoji.mjs changes the list. Needs `cwebp` (libwebp): its lossless
 * encoder writes sheets a quarter the size of the image crate's.
 */

import { readFileSync, writeFileSync, existsSync, rmSync, mkdirSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { execFileSync } from 'child_process';
import vm from 'vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SVG_DIR = join(ROOT, 'src', 'twemoji', 'svg');
const CELL = Number(process.argv[2] || 72);
const OUT_DIR = process.argv[3] || join(ROOT, 'src', 'twemoji', 'sheets');
const MAP_JS = join(ROOT, 'src', 'js', 'emoji', 'sheets.js');
const PER = 128;
const COLS = 16;

// The picker's list, in its order.
const src = readFileSync(join(ROOT, 'src', 'js', 'emoji.js'), 'utf8');
const start = src.indexOf('[', src.indexOf('const arrEmojis'));
const emojis = vm.runInNewContext(src.slice(start, src.indexOf('];', start) + 1));

// The file twemoji draws each one from, as the app's twemojify asks for it.
const ctx = {};
vm.createContext(ctx);
vm.runInContext(readFileSync(join(ROOT, 'src', 'js', 'twemoji.min.js'), 'utf8') + ';this.twemoji = twemoji;', ctx);
const iconOf = (emoji) => {
    const text = emoji.replace(/[\u{1F3FB}-\u{1F3FF}]/gu, '').replace(/\u{1F441}\u{FE0F}?\u{200D}\u{1F5E8}\u{FE0F}?/gu, '\u{1F441}\u{200D}\u{1F5E8}');
    const icons = [];
    ctx.twemoji.parse(text, { callback: (icon) => { icons.push(icon); return false; } });
    return icons.length === 1 ? icons[0] : null;
};

const slots = {};
const icons = [];
for (const { emoji } of emojis) {
    const icon = iconOf(emoji);
    if (!icon || slots[emoji] !== undefined || !existsSync(join(SVG_DIR, `${icon}.svg`))) continue;
    slots[emoji] = icons.length;
    icons.push(icon);
}

const list = join(ROOT, 'scripts', '.twemoji-sheets.txt');
writeFileSync(list, icons.join('\n'));
rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });
execFileSync('cargo', ['run', '--quiet', '--release', '-p', 'vector-core', '--example', 'twemoji_sheets', '--', list, SVG_DIR, OUT_DIR, String(CELL), String(PER), String(COLS)], { cwd: join(ROOT, 'crates'), stdio: 'inherit' });
rmSync(list);
for (const png of readdirSync(OUT_DIR).filter((f) => f.endsWith('.png'))) {
    const path = join(OUT_DIR, png);
    execFileSync('cwebp', ['-quiet', '-lossless', '-z', '9', path, '-o', path.replace(/\.png$/, '.webp')], { stdio: 'inherit' });
    rmSync(path);
}

if (OUT_DIR === join(ROOT, 'src', 'twemoji', 'sheets')) {
    writeFileSync(MAP_JS, `/** Auto-generated by scripts/build-twemoji-sheets.mjs — do not edit by hand */

/** Where each stock emoji sits in src/twemoji/sheets: sheet \`slot / per\`, cell \`slot % per\`, \`cols\` across. */
const twemojiSheets = { per: ${PER}, cols: ${COLS}, count: ${icons.length}, slots: ${JSON.stringify(slots)} };
`);
}
console.log(`${icons.length} of ${emojis.length} emoji packed, ${CELL} px cells`);
